import { defineFunction } from "@aws-amplify/backend";

/**
 * データ整合性の日次監視（2026-09-04 最終フェーズ Phase B）。
 *
 * ── 何をするか ──────────────────────────────────────────────────
 *
 * 1日1回、実データを**読むだけ**で孤児・重複・途中状態を数え、
 * 前回の基準値と比べる。増えていたら記録し、通知できる形にする。
 *
 * **自動修復は一切しない。** 削除・統合・書き換えのコードはこのLambdaに
 * 存在しない（IAMでも、監視ログのテーブル以外への書き込みを与えていない）。
 *
 * ── なぜ新しいサービスを足さないのか ────────────────────────────
 *
 * `defineFunction({ schedule })` が Amplify Gen2 のネイティブ機能として
 * EventBridge Scheduler を配線する。既に pricing-scheduler /
 * image-processing-worker / zaico-sync-worker が同じ形で動いており、
 * 新しいサービスの導入にはならない。判定ロジックは lib/integrity/ に
 * 純粋関数として置き、手元の `npm run verify:data-integrity` と
 * **同じコードを共有**する（2箇所に書くと必ずずれる）。
 *
 * ── 頻度と費用 ──────────────────────────────────────────────────
 *
 * 日次。UTCの0時＝日本時間の朝9時に走るので、業務開始時には結果が出ている。
 *
 * 1回の走査で読むのは在庫5,329件・履歴28,423件ほか、合わせて約4万件。
 * 射影で必要な属性だけに絞ってあるので転送は数MB。DynamoDBはオンデマンド
 * 課金で、月30回でも読み取り容量は数万RCU程度にとどまる。Lambdaも月30回・
 * 各数十秒。**公開料金からの概算で月あたり数十円未満**で、現在の運用費に
 * 対して誤差の範囲（実際の請求は請求ダッシュボードで確認のこと）。
 *
 * ── 失敗しても黙らない ──────────────────────────────────────────
 *
 * 走査に失敗した項目は「0件」ではなく「取得できなかった」として記録し、
 * **その項目の基準値を書き換えない**。0で上書きすると、翌日に本来の件数へ
 * 戻ったときに「大量の異常が発生した」と誤検知する。
 */
export const integrityMonitor = defineFunction({
  name: "integrity-monitor",
  entry: "./handler.ts",
  // pricing-scheduler と同じ理由で data スタックへ置く。
  // Amplify Data 管理下のテーブルを直接読むため、function → data の
  // 依存が生まれ、既定の function スタックに置くと data ⇄ function の
  // 循環参照で全デプロイが止まる（resource.ts のコメント参照）。
  resourceGroupName: "data",
  // 4万件規模の並列Scanで、手元からの実測は数十秒。往復の速いLambda内
  // ではもっと短いが、データが増えても打ち切られないよう余裕を持たせる。
  timeoutSeconds: 300,
  memoryMB: 512,
  // 日次。UTC 0時 = JST 朝9時。
  schedule: "every day",
});
