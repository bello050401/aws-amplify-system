const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const source = path.join(root, "mobile", "dist");
const target = path.join(root, "public", "staff-app");
if (!fs.existsSync(path.join(source, "index.html"))) throw new Error("Export the staff app before packaging it.");
fs.mkdirSync(target, { recursive: true });
fs.cpSync(source, target, { recursive: true });
const iconName="bello-system-icon-v1.png";
fs.copyFileSync(path.join(root,"mobile","assets","bello-system-icon.png"),path.join(target,iconName));
const htmlPath=path.join(target,"index.html");
const html=fs.readFileSync(htmlPath,"utf8").replace("</head>",'<link rel="apple-touch-icon" href="/staff-app/'+iconName+'"/><link rel="manifest" href="/staff-app/manifest.webmanifest"/><meta name="apple-mobile-web-app-title" content="Bello SYSTEM"/></head>');
fs.writeFileSync(htmlPath,html);
fs.writeFileSync(path.join(target,"manifest.webmanifest"),JSON.stringify({id:"/staff-app/",name:"Bello SYSTEM",short_name:"Bello",start_url:"/staff-app/index.html",scope:"/staff-app/",display:"standalone",background_color:"#FFF0DC",theme_color:"#FFF0DC",icons:[{src:"/staff-app/"+iconName,sizes:"1254x1254",type:"image/png",purpose:"any"}]}));
console.log("Staff app packaged for BELLO's authenticated origin.");
