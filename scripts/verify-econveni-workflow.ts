import assert from "node:assert/strict";
import { GetCommand, TransactWriteCommand, UpdateCommand } from "@aws-sdk/lib-dynamodb";
import { initialEconveniWorkflow, reserveEconveniOperation, EconveniWorkflowStore, EconveniWorkflowError } from "../lib/listing/econveni/workflowStore";
async function main() {
 const original=initialEconveniWorkflow("inventory-test-one");
 const saving=reserveEconveniOperation(original,"SAVE","hash","op-1")!;
 assert.equal(saving.save.state,"PENDING");assert.equal(original.save.state,"NOT_STARTED");
 assert.throws(()=>reserveEconveniOperation(saving,"SAVE","hash","op-2"),/VERIFY_REQUIRED/);
 const saved={...saving,save:{...saving.save,state:"SUCCEEDED" as const,productId:"123"}};
 assert.equal(reserveEconveniOperation(saved,"SAVE","hash","op-2"),null);
 const updating=reserveEconveniOperation(saved,"SAVE","changed-hash","op-2")!;
 assert.equal(updating.save.productId,"123","Update must preserve the existing binding");
 assert.equal(updating.save.state,"PENDING");
 const yahoo=reserveEconveniOperation(saved,"YAHOO","hash","op-3")!;
 assert.equal(yahoo.channels.YAHOO.state,"PENDING");assert.equal(yahoo.channels.MERCARI_SHOPS.state,"NOT_STARTED");
 assert.throws(()=>reserveEconveniOperation(yahoo,"MERCARI_SHOPS","hash","op-4"),/VERIFY_REQUIRED/);
 const published={...yahoo,channels:{...yahoo.channels,YAHOO:{state:"SUCCEEDED" as const,listingId:"yahoo-1"}}};
 assert.equal(reserveEconveniOperation(published,"YAHOO","hash","op-5"),null);
 const mercari=reserveEconveniOperation(published,"MERCARI_SHOPS","hash","op-6")!;
 assert.equal(mercari.channels.YAHOO.listingId,"yahoo-1");
 const calls:any[]=[];let lastSentAt=0,fail=false;
 const client={send:async(command:any)=>{calls.push(command);if(fail)throw Error("private database exception");return command instanceof GetCommand?{Item:{lastSentAt}}:{};}};
 const store=new EconveniWorkflowStore("inventory-test-one",client as any,"server-only-queue");
 await store.acquire();const lock=calls.at(-1);assert.ok(lock instanceof UpdateCommand);assert.match(lock.input.ConditionExpression!,/attribute_not_exists\(blockedReason\)/);
 const result=await store.commit(null,saving,true);assert.equal(result.revision,1);
 const write=calls.at(-1);assert.ok(write instanceof TransactWriteCommand);
 const reservation=write.input.TransactItems?.[0]?.Update;const item=write.input.TransactItems?.[1]?.Put;
 assert.ok(reservation?.Key);assert.ok(item);
 assert.equal(reservation.Key.pk,"ECONVENI#ACCOUNT");assert.match(reservation.ConditionExpression!,/lastSentAt <= :cutoff/);
 assert.match(reservation.UpdateExpression!,/leaseUntil=:until/);
 assert.ok(reservation.ExpressionAttributeValues![":until"] > Date.now()+170_000,"Reserve refreshes the lease before the external write");
 assert.equal(item.ConditionExpression,"attribute_not_exists(pk)");
 lastSentAt=Date.now();const before=calls.filter(c=>c instanceof TransactWriteCommand).length;
 await assert.rejects(store.commit(result,saving,true),e=>e instanceof EconveniWorkflowError&&e.code==="WAIT_INTERVAL");
 assert.equal(calls.filter(c=>c instanceof TransactWriteCommand).length,before);
 await assert.rejects(store.commit(result,initialEconveniWorkflow("other-inventory")));
 lastSentAt=0;fail=true;await assert.rejects(store.commit(result,saved),e=>e instanceof EconveniWorkflowError&&e.code==="STATE_UNAVAILABLE");
 fail=false;await store.stop("ACCESS_DENIED");assert.equal(calls.at(-1).input.ExpressionAttributeValues[":reason"],"ACCESS_DENIED");
 await store.release();assert.ok(!calls.at(-1).input.UpdateExpression.includes("blockedReason"));
 console.log("PASS: per-channel results, saved content reuse, uncertain write protection, inventory identity, atomic lease/revision reservation, 30s account-wide interval, persistent auth stop");
}
void main().catch(e=>{console.error(e);process.exitCode=1;});
