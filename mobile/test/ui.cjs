const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');

async function run() {
  const target = process.env.MOBILE_UI_PROOF_DIR;
  if (!target) throw new Error('MOBILE_UI_PROOF_DIR is required.');
  await fs.mkdir(target, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://localhost:8097', { waitUntil: 'networkidle', timeout: 60000 });
    await expect(page.getByText('操作確認用・実在庫には反映しません')).toBeVisible();
    await expect(page.getByRole('tab')).toHaveCount(4);
    for (const name of ['ホーム', '在庫一覧', 'EC出品', '売上']) await expect(page.getByRole('tab', { name, exact: true })).toBeVisible();
    await expect(page.getByText('ラベル印刷', { exact: true })).toHaveCount(0);
    await page.screenshot({ path: path.join(target, 'home.png') });
    await page.getByRole('tab', { name: 'EC出品', exact: true }).click();
    await page.getByRole('button', { name: '表示確認アカウントを切り替え', exact: true }).click();
    await expect(page.getByText('表示確認：スタッフ', { exact: true })).toBeVisible();
    await expect(page.getByRole('tab')).toHaveCount(2);
    await expect(page.getByText('EC出品', { exact: true })).toHaveCount(0);
    await expect(page.getByText('売上', { exact: true })).toHaveCount(0);
    await expect(page.getByRole('button', { name: '新規登録', exact: true })).toBeVisible();
    await page.screenshot({ path: path.join(target, 'staff-home.png') });
    await page.getByRole('tab', { name: '在庫一覧', exact: true }).click();
    await expect(page.getByRole('button', { name: 'ダイニングチェア / ナチュラルウッド、数量11', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '表示確認アカウントを切り替え', exact: true }).click();
    await expect(page.getByRole('tab')).toHaveCount(4);
    await page.getByRole('tab', { name: '売上', exact: true }).click();
    await page.getByRole('button', { name: '表示確認アカウントを切り替え', exact: true }).click();
    await expect(page.getByText('売上', { exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: '表示確認アカウントを切り替え', exact: true }).click();
    await page.getByRole('tab', { name: '在庫一覧', exact: true }).click();
    await expect(page.getByRole('button', { name: 'ダイニングチェア / ナチュラルウッド、数量11', exact: true })).toBeVisible();
    await page.screenshot({ path: path.join(target, 'inventory.png') });
    await page.getByRole('button', { name: 'ダイニングチェア / ナチュラルウッド、数量11', exact: true }).click();
    await page.getByRole('button', { name: '編集', exact: true }).click();
    await page.getByLabel('数量', { exact: true }).fill('14');
    await expect(page.getByText('変更内容をどうしますか？')).toHaveCount(0);
    await page.getByRole('button', { name: '圏外を試す', exact: true }).click();
    await page.getByRole('button', { name: '完了', exact: true }).click();
    await expect(page.getByText('【圏外です】', { exact: true })).toBeVisible();
    await expect(page.getByLabel('数量', { exact: true })).toHaveValue('14');
    await page.getByRole('button', { name: '一覧へ戻る', exact: true }).click();
    await expect(page.getByText('変更内容をどうしますか？')).toBeVisible();
    await page.getByRole('button', { name: '変更を保存する', exact: true }).click();
    await expect(page.getByText('変更内容をどうしますか？')).toBeVisible();
    await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))); });
    await page.screenshot({ path: path.join(target, 'offline-confirmation.png') });
    await page.getByRole('button', { name: '編集を続ける', exact: true }).click();
    await expect(page.getByLabel('数量', { exact: true })).toHaveValue('14');
    await page.getByRole('button', { name: '通信を戻す', exact: true }).click();
    await expect(page.getByLabel('数量', { exact: true })).toHaveValue('14');
    await expect(page.getByText('在庫の編集', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '一覧へ戻る', exact: true }).click();
    await page.getByRole('button', { name: '変更を保存する', exact: true }).click();
    await expect(page.getByRole('button', { name: 'ダイニングチェア / ナチュラルウッド、数量14', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'ダイニングチェア / ナチュラルウッド、数量14', exact: true }).click();
    await page.getByRole('button', { name: '編集', exact: true }).click();
    await page.getByLabel('数量', { exact: true }).fill('999');
    await page.getByRole('button', { name: '一覧へ戻る', exact: true }).click();
    await page.getByRole('button', { name: '変更内容を破棄する', exact: true }).click();
    await expect(page.getByRole('button', { name: 'ダイニングチェア / ナチュラルウッド、数量14', exact: true })).toBeVisible();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    if (overflow || errors.length) throw new Error(JSON.stringify({ overflow, errors }));
    await fs.writeFile(path.join(target, 'ui-result.json'), JSON.stringify({ passed: true, viewport: '390x844', mode: 'React Native Web developer preview, synthetic data and simulated connectivity', scenarios: ['four tabs', 'no printing', 'staff hides EC and sales including an open screen', 'staff retains inventory access', 'offline save retains edit', 'leave confirmation only', 'offline save does not navigate', 'continue retains draft', 'reconnect does not autosave', 'explicit save reflects result', 'discard does not change saved inventory', 'no horizontal overflow'], nativeDeviceVerified: false, productionVerified: false }, null, 2));
    console.log('PASS: 12 mobile UI scenarios; synthetic data only. iPhone device verification remains.');
  } finally { await browser.close(); }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
