/**
 * サーバ起動時に1回だけ走る Next.js の公式フック。
 *
 * ── なぜこれを置くのか ──────────────────────────────────────────
 *
 * Amplify Hosting の SSR(WEB_COMPUTE)は、アプリが標準出力へ書いたものを
 * CloudWatch の `/aws/amplify/<appId>` へ送る。設定項目は無く、**出力が
 * あったときに初めてロググループが作られる**。
 *
 * ところが調査時点で、このアカウントには `/aws/amplify/*` が1つも無かった:
 *
 *   ロググループ全22個 … すべてバックエンドLambda。SSR分は存在しない
 *   コンピュートロール … logs:CreateLogGroup / PutLogEvents を
 *                        /aws/amplify/* に対して許可済み(権限は足りている)
 *   サービスロール     … AdministratorAccess-Amplify
 *   platform           … WEB_COMPUTE、直近のデプロイも成功
 *
 * 公開ルートへ実際にリクエストを流しても作られなかった。正常応答では
 * アプリが何も書かないので、当然といえば当然。
 *
 * つまり「ログ配信が壊れている」のか「まだ何も出力していないだけ」なのかが
 * 区別できない状態だった。**次に本番でエラーが起きたときに初めて分かる**
 * のでは遅い —— そのときに限って何も残らない、が一番困る。
 *
 * ここで起動時に1行だけ出す。ロググループができれば配信は生きていると
 * 確定し、できなければ配信側の問題だと確定する。どちらでも前進する。
 *
 * ── 出す内容 ────────────────────────────────────────────────────
 *
 * 秘密は一切含めない。環境変数の値も出さない(名前すら出さない)。
 * 出すのは「いつ起動したか」と「どのNode.jsか」だけ。
 *
 * ── 量 ──────────────────────────────────────────────────────────
 *
 * コンピュートインスタンスの起動ごとに1行。リクエストごとではないので、
 * ログが膨らむことはない。
 */
export async function register() {
  // Edge ランタイムでは実行しない(SSRコンピュートの確認が目的のため)。
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  console.info(
    "[bello] server started",
    JSON.stringify({
      at: new Date().toISOString(),
      node: process.version,
      // NODE_ENV は値そのものが秘密ではなく、production かどうかの確認に要る
      // (E2E認証バイパスが構造的に無効であることの裏付けにもなる)。
      env: process.env.NODE_ENV,
    }),
  );
}
