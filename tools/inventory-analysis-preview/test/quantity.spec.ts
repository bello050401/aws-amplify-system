import { expect, test } from "@playwright/test";

test("320px Web calculation, stable save retry, reload, latest replacement, and changed source", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 730 });
  await page.goto("/quantity?fixture=retry");
  await page.getByRole("button", { name: "適正数量の計算" }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("heading", { name: /オーク無垢材 ベンチ/ })).toBeVisible();
  await expect(dialog.getByText("家具ブランド（見本）", { exact: false })).toBeVisible();
  await expect(dialog.getByText("5,000円", { exact: true })).toBeVisible();
  await expect(dialog.getByText("40,000円", { exact: true })).toBeVisible();
  await expect(dialog.getByText("8,500円", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("img", { name: "商品画像（見本）" })).toBeVisible();
  await expect(dialog.getByLabel(/予定販売価格/)).toHaveCount(0);
  const maintenance = dialog.getByLabel(/残りのメンテナンス時間/);
  await expect(maintenance).toHaveValue("");
  await expect(dialog.getByRole("radio", { checked: true })).toHaveCount(0);
  const months = dialog.getByLabel("販売期間（ヶ月）");
  const count = dialog.getByLabel("販売見込み（個）");
  await months.fill("0");
  await count.fill("-1");
  await dialog.getByRole("button", { name: "計算する" }).click();
  await expect(dialog.getByRole("alert")).toContainText("月数に正の数");
  await expect(dialog.getByRole("alert")).toContainText("1以上の整数");
  await months.fill("0.5");
  await count.fill("1");
  await maintenance.selectOption("0");
  await dialog.getByRole("radio", { name: "重ねる" }).check();
  await dialog.getByRole("button", { name: "計算する" }).click();
  await expect(dialog.getByText("通常販売に残す", { exact: true })).toBeVisible();
  await expect(dialog.getByText("業販に回す", { exact: true })).toBeVisible();
  await expect(dialog.getByText(/保管面積はカテゴリ標準値による推定/)).toBeVisible();
  await expect(dialog.getByText("4㎡（1.21坪）")).toBeVisible();
  const quantities = await dialog.locator("p").filter({ hasText: /^\d+個$/ }).allTextContents();
  expect(quantities).toHaveLength(2);
  expect(quantities.reduce((sum, value) => sum + Number.parseInt(value), 0)).toBe(8);
  await dialog.getByText("価格・販売ペース・費用・面積の詳細").click();
  await expect(dialog.getByText("半分の販売ペースでの推奨")).toBeVisible();
  await expect(dialog.getByText("未計上", { exact: true })).toBeVisible();
  await months.fill("1");
  const save = dialog.getByRole("button", { name: "計算結果を保存" });
  await expect(save).toBeDisabled();
  await expect(dialog.getByText(/計算条件が変更されています/)).toBeVisible();
  await dialog.getByRole("button", { name: "再計算", exact: true }).click();
  await expect(save).toBeEnabled();
  await expect(dialog.evaluate(box => box.scrollWidth <= box.clientWidth)).resolves.toBeTruthy();
  await save.click();
  await expect(dialog.getByRole("alert")).toContainText("入力した条件で再試行");
  await expect(months).toHaveValue("1");
  await save.click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole("heading", { name: "保存済みの計算結果" })).toBeVisible();
  await page.goto("/quantity");
  await expect(page.getByRole("heading", { name: "保存済みの計算結果" })).toBeVisible();
  await page.getByRole("button", { name: "適正数量の計算" }).click();
  await expect(months).toHaveValue("1");
  await expect(count).toHaveValue("1");
  await expect(maintenance).toHaveValue("0");
  await expect(dialog.getByRole("radio", { name: "重ねる" })).toBeChecked();
  await dialog.getByRole("button", { name: "計算する" }).click();
  await save.click();
  await expect(page.getByRole("heading", { name: "保存済みの計算結果" })).toHaveCount(1);
  await page.goto("/quantity?fixture=changed");
  await expect(page.getByText(/再計算が必要です。在庫または計算設定が更新/)).toBeVisible();
  await page.getByRole("button", { name: "適正数量の計算" }).click();
  await expect(dialog.getByText("35,000円", { exact: true })).toBeVisible();
  await expect(months).toHaveValue("1");
  await expect(save).toHaveCount(0);
});

test("price registration, viewer permission, missing source, and area settings guidance", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 800 });
  async function open(mode: string) {
    await page.goto("/quantity?fixture=" + mode);
    await page.getByRole("button", { name: "適正数量の計算" }).click();
    return page.getByRole("dialog");
  }
  let dialog = await open("zero");
  await expect(dialog.getByLabel(/予定販売価格/)).toHaveCount(0);
  await expect(dialog.getByText("0円", { exact: true })).toBeVisible();

  dialog = await open("unregistered");
  await expect(dialog.getByLabel(/予定販売価格/)).toBeVisible();
  await dialog.getByLabel(/予定販売価格/).fill("9500");
  await dialog.getByLabel("販売期間（ヶ月）").fill("28");
  await dialog.getByLabel("販売見込み（個）").fill("8");
  await dialog.getByLabel(/残りのメンテナンス時間/).selectOption("0");
  await dialog.getByRole("radio", { name: "平置き" }).check();
  await dialog.getByRole("button", { name: "計算する" }).click();
  await dialog.getByText("価格・販売ペース・費用・面積の詳細").click();
  await expect(dialog.getByText(/28ヶ月$/, { exact: false })).toBeVisible();
  await expect(dialog.getByText(/9,500円.*計算条件の補完価格/)).toBeVisible();
  await dialog.getByRole("button", { name: "計算結果を保存" }).click();
  await page.reload();
  await page.getByRole("button", { name: "適正数量の計算" }).click();
  await expect(page.getByRole("dialog").getByLabel(/予定販売価格/)).toHaveValue("9500");

  dialog = await open("viewer");
  await dialog.getByLabel("販売期間（ヶ月）").fill("0.5");
  await dialog.getByLabel("販売見込み（個）").fill("1");
  await dialog.getByLabel(/残りのメンテナンス時間/).selectOption("0");
  await dialog.getByRole("radio", { name: "平置き" }).check();
  await dialog.getByRole("button", { name: "計算する" }).click();
  await expect(dialog.getByText("業販に回す", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "計算結果を保存" })).toHaveCount(0);

  dialog = await open("stock-missing");
  await expect(dialog.getByRole("alert")).toContainText("購入単価が未登録");
  await expect(dialog.getByRole("button", { name: "計算する" })).toBeDisabled();
  await dialog.getByRole("link", { name: "在庫を編集する" }).click();
  await expect(page.getByRole("heading", { name: "既存在庫編集（検証用の遷移先）" })).toBeVisible();

  dialog = await open("no-area");
  await dialog.getByLabel("販売期間（ヶ月）").fill("0.5");
  await dialog.getByLabel("販売見込み（個）").fill("1");
  await dialog.getByLabel(/残りのメンテナンス時間/).selectOption("0");
  await dialog.getByRole("radio", { name: "重ねる" }).check();
  await dialog.getByRole("button", { name: "計算する" }).click();
  await expect(dialog.getByRole("alert")).toContainText("保管面積を確定できません");
  await dialog.getByRole("link", { name: "カテゴリの保管面積設定を開く" }).click();
  await page.getByRole("button", { name: "カテゴリ標準を追加" }).click();
  await page.getByLabel("商品カテゴリ").selectOption("bench");
  await page.getByLabel("保管方法").selectOption("disassembled");
  await page.getByLabel("標準の種類").selectOption("measured-category");
  await expect(page.getByText(/天板、脚、金具、養生、支持具/)).toBeVisible();
  await page.getByLabel("1区画あたりの面積（㎡）").fill("2");
  await page.getByLabel("1区画の収納数（個）").fill("4");
  await page.getByLabel("分解時間（分／1個）").fill("0");
  await page.getByLabel("再組立時間（分／通常販売1個）").fill("15");
  await page.getByLabel("測定・見積もりの根拠").fill("実測見本");
  await page.getByRole("button", { name: "適正数量の設定を保存" }).click();
  await expect(page.getByRole("status")).toHaveText("適正数量の設定を保存しました。");
  await page.reload();
  await expect(page.getByLabel("測定・見積もりの根拠")).toHaveValue("実測見本");
});

test("an open proposal detects updated stock on focus and again at save", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 800 });
  await page.goto("/quantity?fixture=live-change");
  await page.getByRole("button", { name: "適正数量の計算" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("販売期間（ヶ月）").fill("0.5");
  await dialog.getByLabel("販売見込み（個）").fill("1");
  await dialog.getByLabel(/残りのメンテナンス時間/).selectOption("0");
  await dialog.getByRole("radio", { name: "重ねる" }).check();
  await dialog.getByRole("button", { name: "計算する" }).click();
  const save = dialog.getByRole("button", { name: "計算結果を保存" });
  await expect(save).toBeEnabled();
  await page.evaluate(() => {
    localStorage.setItem("bello-quantity-preview:changed", "1");
    document.dispatchEvent(new Event("visibilitychange"));
  });
  await expect(dialog.getByText(/元の在庫または設定が更新/)).toBeVisible();
  await expect(save).toBeDisabled();
  await expect(dialog.getByText("35,000円", { exact: true })).toBeVisible();
  await expect(dialog.getByLabel("販売期間（ヶ月）")).toHaveValue("0.5");
  await dialog.getByRole("button", { name: "再計算", exact: true }).click();
  await expect(save).toBeEnabled();
  await page.evaluate(() => localStorage.removeItem("bello-quantity-preview:changed"));
  await save.click();
  await expect(dialog.getByRole("alert")).toContainText("再計算が必要です");
  await expect(save).toBeDisabled();
  await expect(dialog.getByText("40,000円", { exact: true })).toBeVisible();
  await expect(dialog.getByLabel("販売期間（ヶ月）")).toHaveValue("0.5");
  await dialog.getByRole("button", { name: "再計算", exact: true }).click();
  await save.click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole("heading", { name: "保存済みの計算結果" })).toBeVisible();
});
